/**
 * Handing a file to Android.
 *
 * Inside the app a download is a dead end, so the G-code crosses the JS bridge
 * in pieces and is written to a file on the native side. The demo cube is a
 * quarter of a megabyte — one piece. A real model is tens of megabytes —
 * dozens of them. That difference is exactly where a file quietly loses its
 * second half, and a printer given half a file levels the bed, heats up, prints
 * part of the job and stops.
 *
 * So: a stand-in bridge that reassembles what it is given, and one that drops a
 * piece on purpose. The bytes have to arrive intact, and a loss has to be said
 * out loud rather than saved.
 *
 *   python3 -m http.server 8099   (from the repo root)
 *   node test-ui-android-save.js
 */
const { chromium } = require('playwright');

const APP = process.env.APP || 'http://localhost:8099/index.html';

(async () => {
  const browser = await chromium.launch({
    executablePath: process.env.CHROME || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome'
  });
  const page = await browser.newPage({ viewport: { width: 1400, height: 950 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));

  let pass = 0, fail = 0;
  const ok = (label, cond, detail) => {
    if (cond) { pass++; console.log('  ok    ' + label); }
    else { fail++; console.log('  FAIL  ' + label + (detail ? '  -> ' + detail : '')); }
  };

  const alerts = [];
  page.on('dialog', d => { alerts.push(d.message()); d.accept(); });

  await page.goto(APP);
  await page.waitForSelector('#btn-slice');

  /**
   * Install a stand-in for the native side. It keeps what it is handed, counts
   * the bytes the way Java would, and can be told to lose one piece.
   */
  const installBridge = (loseChunk) => page.evaluate((lose) => {
    const state = { name: null, parts: [], bytes: 0, ended: false, discarded: false, calls: 0 };
    window.__android = state;
    window.AndroidSlicer = {
      beginSave(name) { state.name = name; state.parts = []; state.bytes = 0; return true; },
      appendSave(chunk) {
        state.calls++;
        // A piece dropped in the bridge: it reports success and writes nothing,
        // which is the failure worth catching.
        if (lose >= 0 && state.calls === lose) return true;
        state.parts.push(chunk);
        state.bytes += new TextEncoder().encode(chunk).length;
        return true;
      },
      pendingBytes() { return String(state.bytes); },
      discardSave() { state.discarded = true; state.parts = []; },
      endSave() { state.ended = true; }
    };
  }, loseChunk);

  // A file the size of a real model's G-code, with the awkward things in it:
  // a chunk boundary is 64 KB, so this crosses dozens of them.
  const makeBig = () => page.evaluate(() => {
    const line = 'G1 X123.456 Y98.765 E12.3456 F1800\n';
    let g = '; generated by Orca Web Slicer\n; modèle — accentué, and an emoji 🧊\n';
    while (g.length < 9 * 1024 * 1024) g += line;
    window.__gcode = g;
    return { chars: g.length, bytes: new TextEncoder().encode(g).length };
  });

  const size = await makeBig();
  ok('a model-sized file to hand over (' + Math.round(size.bytes / 1048576) + ' MB, ' +
    (size.bytes - size.chars) + ' bytes more than characters)',
    size.bytes > 9000000 && size.bytes > size.chars, JSON.stringify(size));

  // --- the whole file, in one piece at the far end -------------------------
  await installBridge(-1);
  const good = await page.evaluate(() => {
    const okStream = window.OrcaSlicerTest.streamToAndroid('model.gcode', window.__gcode);
    const joined = window.__android.parts.join('');
    return {
      okStream: okStream,
      calls: window.__android.calls,
      identical: joined === window.__gcode,
      bytes: window.__android.bytes,
      expected: new TextEncoder().encode(window.__gcode).length
    };
  });
  ok('it crosses in many pieces (' + good.calls + ')', good.calls > 100, String(good.calls));
  ok('and comes back together exactly as it went in', good.identical);
  ok('with every byte accounted for (' + good.bytes + ')', good.bytes === good.expected,
    good.bytes + ' vs ' + good.expected);
  ok('so the hand-over reports success', good.okStream === true);
  ok('and nothing was said to the user', alerts.length === 0, JSON.stringify(alerts));

  // --- a piece lost on the way --------------------------------------------
  alerts.length = 0;
  await installBridge(7);
  const lost = await page.evaluate(() => {
    const okStream = window.OrcaSlicerTest.streamToAndroid('model.gcode', window.__gcode);
    return { okStream: okStream, discarded: window.__android.discarded, ended: window.__android.ended };
  });
  ok('a lost piece is not reported as a saved file', lost.okStream === false);
  ok('the half-written file is thrown away rather than kept', lost.discarded === true);
  ok('and the user is told, in bytes, what went missing',
    alerts.length === 1 && /bytes arrived/.test(alerts[0]), JSON.stringify(alerts));
  console.log('  said: ' + (alerts[0] || '').slice(0, 120));

  // --- a bridge too old to count ------------------------------------------
  // The check must not turn into a new way to fail on a device whose app has
  // not been updated.
  alerts.length = 0;
  await page.evaluate(() => {
    const state = { parts: [], calls: 0 };
    window.__android = state;
    window.AndroidSlicer = {
      beginSave() { state.parts = []; return true; },
      appendSave(c) { state.calls++; state.parts.push(c); return true; },
      endSave() {}
    };
  });
  const oldBridge = await page.evaluate(() =>
    window.OrcaSlicerTest.streamToAndroid('model.gcode', window.__gcode));
  ok('a bridge with no counter still saves', oldBridge === true);
  ok('and says nothing about it', alerts.length === 0, JSON.stringify(alerts));

  ok('no console errors', errors.length === 0, errors.slice(0, 3).join(' | '));
  await browser.close();
  console.log('\n' + pass + ' passed, ' + fail + ' failed');
  process.exit(fail ? 1 : 0);
})();
